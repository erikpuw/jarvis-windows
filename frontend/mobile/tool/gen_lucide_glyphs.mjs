// Generates lib/chat/lucide_glyphs.dart from the lucide package (ISC, version 1.48 - the one the web frontend uses).
// Run from anywhere: node tool/gen_lucide_glyphs.mjs <path to lucide/dist/esm/icons>
//   e.g. node tool/gen_lucide_glyphs.mjs E:/workspace/jarvis/frontend/node_modules/lucide/dist/esm/icons
// The output path is fixed relative to this script (../lib/chat/lucide_glyphs.dart), not to the working directory.
import { writeFileSync } from 'node:fs';
import { pathToFileURL } from 'node:url';
import { join } from 'node:path';

const outFile = new URL('../lib/chat/lucide_glyphs.dart', import.meta.url);

const dir = process.argv[2];
const names = `menu x mic mic-off volume-2 volume-x square-terminal chevron-down plus paperclip loader-circle circle-dashed
save plug-zap upload trash refresh-cw house
layout-dashboard layout-grid key-round key audio-lines user-round user-check cpu activity database hard-drive file-clock
scroll-text bot bot-message-square webhook anchor sparkles flame file-text terminal square-code puzzle plug boxes network
workflow git-fork book-open info panel-left panel-left-close
brain lightbulb rotate-cw target check-check wrench hammer message-square messages-square dumbbell dna sprout
search chevron-left chevron-right shield-alert`.split(/\s+/);
const camel = (s) => s.replace(/-(\w)/g, (_, c) => c.toUpperCase());
const n = (v) => +(+v).toFixed(4);
function ellipse(cx, cy, rx, ry) {
  const e = cx + rx, w = cx - rx, s = cy + ry, t = cy - ry;
  return `M${n(e)} ${n(cy)}A${n(rx)} ${n(ry)} 0 0 1 ${n(cx)} ${n(s)}A${n(rx)} ${n(ry)} 0 0 1 ${n(w)} ${n(cy)}A${n(rx)} ${n(ry)} 0 0 1 ${n(cx)} ${n(t)}A${n(rx)} ${n(ry)} 0 0 1 ${n(e)} ${n(cy)}Z`;
}
function rect(a) {
  const x = +(a.x ?? 0), y = +(a.y ?? 0), w = +a.width, h = +a.height;
  let rx = a.rx ?? a.ry ?? 0, ry = a.ry ?? a.rx ?? 0;
  rx = Math.min(Math.max(+rx, 0), w / 2); ry = Math.min(Math.max(+ry, 0), h / 2);
  if (!rx || !ry) return `M${x} ${y}H${n(x + w)}V${n(y + h)}H${x}Z`;
  const r = `${n(rx)} ${n(ry)} 0 0 1`;
  return `M${n(x + rx)} ${y}H${n(x + w - rx)}A${r} ${n(x + w)} ${n(y + ry)}V${n(y + h - ry)}A${r} ${n(x + w - rx)} ${n(y + h)}H${n(x + rx)}A${r} ${x} ${n(y + h - ry)}V${n(y + ry)}A${r} ${n(x + rx)} ${y}Z`;
}
function toD([tag, a]) {
  switch (tag) {
    case 'path': return a.d;
    case 'line': return `M${a.x1} ${a.y1}L${a.x2} ${a.y2}`;
    case 'circle': return ellipse(+a.cx, +a.cy, +a.r, +a.r);
    case 'ellipse': return ellipse(+a.cx, +a.cy, +a.rx, +a.ry);
    case 'rect': return rect(a);
    case 'polyline': case 'polygon': {
      const p = a.points.trim().split(/[\s,]+/);
      let d = `M${p[0]} ${p[1]}`;
      for (let i = 2; i < p.length; i += 2) d += `L${p[i]} ${p[i + 1]}`;
      return d + (tag === 'polygon' ? 'Z' : '');
    }
    default: throw new Error(tag);
  }
}
let out = `// GENERATED by tool/gen_lucide_glyphs.mjs from lucide (ISC, lucide.dev): the icons the web morphs (icons.ts SPECS, settings nav).
// Shapes other than <path> are written as path data, as morphicons lowers them. Do not edit by hand.
import 'morph_icon.dart';

`;
for (const name of names) {
  const node = (await import(pathToFileURL(join(dir, `${name}.mjs`)).href)).default;
  const ds = node.map(toD).map((d) => `  '${d}',`).join('\n');
  out += `const ${camel(name)}Glyph = MorphGlyph([\n${ds}\n]);\n`;
}
writeFileSync(outFile, out);
